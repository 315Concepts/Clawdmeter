//! Extracts the official idle Clawd from the firmware's generated
//! `splash_animations.h` (frame 0 of `waving`, body rows only) so the tray
//! icon and every in-app Clawd come from the real art, never a redraw.
//!
//! Output: `$OUT_DIR/clawd_idle.rs` with `IDLE_W`, `IDLE_H`, `IDLE_CELLS`
//! (palette indices, row-major) and `IDLE_PALETTE` (0xRRGGBB, index 0 =
//! background).

use std::env;
use std::fs;
use std::path::PathBuf;

/// The idle body on the shared 55x37 art stage (spec §01: 24x16 cells).
const BODY_L: usize = 15;
const BODY_T: usize = 21;
const BODY_W: usize = 24;
const BODY_H: usize = 16;
const ANIM: &str = "waving";

fn rgb565_to_888(v: u16) -> u32 {
    let r = ((v >> 11) & 0x1f) as u32;
    let g = ((v >> 5) & 0x3f) as u32;
    let b = (v & 0x1f) as u32;
    let r = (r << 3) | (r >> 2);
    let g = (g << 2) | (g >> 4);
    let b = (b << 3) | (b >> 2);
    (r << 16) | (g << 8) | b
}

/// The comma-separated numbers inside `{ … }` after `marker`.
fn array_after(src: &str, marker: &str) -> Vec<u32> {
    let start = src.find(marker).unwrap_or_else(|| panic!("{marker} not found in splash_animations.h"));
    let open = start + src[start..].find('{').expect("array opens");
    let close = open + src[open..].find('}').expect("array closes");
    src[open + 1..close]
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(|s| {
            if let Some(hex) = s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
                u32::from_str_radix(hex, 16).expect("hex")
            } else {
                s.parse().expect("number")
            }
        })
        .collect()
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let header = manifest.join("../../../firmware/src/splash_animations.h");
    println!("cargo:rerun-if-changed={}", header.display());
    let src = fs::read_to_string(&header)
        .unwrap_or_else(|e| panic!("{}: {e} (the app draws Clawd from the firmware's art)", header.display()));

    // Table row: {"waving", "core", w, h, ox, oy, frames, …}
    let row_marker = format!("{{\"{ANIM}\",");
    let row_start = src.find(&row_marker).expect("animation table row");
    let row_end = row_start + src[row_start..].find('}').expect("row end");
    let fields: Vec<&str> = src[row_start + 1..row_end].split(',').map(str::trim).collect();
    let num = |i: usize| -> usize { fields[i].parse().expect("table number") };
    let (w, h, ox, oy) = (num(2), num(3), num(4), num(5));

    let palette = array_after(&src, &format!("splash_{ANIM}_palette["));
    let frames = array_after(&src, &format!("splash_{ANIM}_frames["));
    assert!(frames.len() >= w * h, "frame 0 present");
    assert!(BODY_L >= ox && BODY_T >= oy && BODY_L - ox + BODY_W <= w && BODY_T - oy + BODY_H <= h, "body inside crop");

    let mut cells = Vec::with_capacity(BODY_W * BODY_H);
    for r in 0..BODY_H {
        for c in 0..BODY_W {
            cells.push(frames[(BODY_T - oy + r) * w + (BODY_L - ox + c)]);
        }
    }
    let pal: Vec<String> = palette.iter().map(|&v| format!("0x{:06x}", rgb565_to_888(v as u16))).collect();
    let cells_s: Vec<String> = cells.iter().map(u32::to_string).collect();
    let out = format!(
        "// Generated by build.rs from firmware/src/splash_animations.h ({ANIM}, frame 0). Do not edit.\n\
         /// Idle body width, cells.\npub const IDLE_W: usize = {BODY_W};\n\
         /// Idle body height, cells.\npub const IDLE_H: usize = {BODY_H};\n\
         /// Palette indices, row-major; 0 = transparent.\npub const IDLE_CELLS: [u8; {n}] = [{cells}];\n\
         /// 0xRRGGBB per palette index (RGB565 expanded).\npub const IDLE_PALETTE: [u32; {pn}] = [{pal}];\n",
        n = cells.len(),
        cells = cells_s.join(","),
        pn = pal.len(),
        pal = pal.join(","),
    );
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("clawd_idle.rs");
    fs::write(dest, out).expect("write clawd_idle.rs");
}
